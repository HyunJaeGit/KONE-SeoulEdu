JOIN faq_categories c ON c.name = r.category_name
ORDER BY r.seq;
SET @reference_faq_count = ROW_COUNT();
SET @first_reference_faq_id = LAST_INSERT_ID();
INSERT INTO faq_usage_stats (faq_id, open_count)
SELECT id, 0 FROM faqs
WHERE id >= @first_reference_faq_id AND id < @first_reference_faq_id + @reference_faq_count;
DROP TEMPORARY TABLE tmp_reference_faqs;
